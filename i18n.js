export function t(language,key,values={}) {
  if(!Object.hasOwn(COPY,key)) throw new Error('Unknown interface copy: '+key);
  return COPY[key][LANGUAGES.indexOf(languageOf(language))].replace(/\{(\w+)\}/g,(_,name)=>
    Object.hasOwn(values,name) && ['string','number'].includes(typeof values[name]) ? String(values[name]) : '');
}

export function translatedCard(card,language) {
  const selected=languageOf(language);
  const version=card.translations && Object.hasOwn(card.translations,selected) ? card.translations[selected] : null;
  const complete=version && ['category','question','answer'].every(key=>typeof version[key]==='string' && version[key].trim() && version[key].length<=2000
    && (selected==='en' ? /[a-z]/i.test(version[key]) : /[\u4e00-\u9fff]/u.test(version[key])))
    && (selected!=='en' || (version.answer.match(/[a-z]+/gi)?.length>=12 && (version.answer.match(/[\u4e00-\u9fff]/gu)?.length || 0)<version.answer.length/4));
  if(selected==='zh-Hant' || !complete) return {card,language:'zh-Hant',fallback:selected!=='zh-Hant'};
  // Localized data may replace prose only, never IDs, attribution, or links.
  return {card:{...card,category:version.category.trim(),question:version.question.trim(),answer:version.answer.trim(),terms:version.terms},language:selected,fallback:false};
}
