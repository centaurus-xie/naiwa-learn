import {build} from 'esbuild';
import {copyFile,readFile,stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const installed=JSON.parse(await readFile(new URL('node_modules/three/package.json',root),'utf8'));
if(installed.version!=='0.186.1') throw new Error('Unexpected Three.js version');
await build({entryPoints:[fileURLToPath(new URL('assets/mascot/three-entry.js',root))],
  outfile:fileURLToPath(new URL('assets/mascot/three.min.js',root)),bundle:true,format:'esm',
  minify:true,target:['es2020'],legalComments:'inline',
  banner:{js:'// Three.js 0.186.1 · MIT · see THREE-LICENSE.txt · generated by npm run vendor:three'}});
await copyFile(new URL('node_modules/three/LICENSE',root),new URL('assets/mascot/THREE-LICENSE.txt',root));
console.log('Local 3D engine: '+(await stat(new URL('assets/mascot/three.min.js',root))).size+' bytes');
